export type Locale = "pt" | "en";

export function detectPreferredLocale(value?: string | null): Locale {
  if (!value) return "pt";
  const languages = value.toLowerCase().split(",").map((entry) => entry.trim().split(";")[0]);
  const englishIndex = languages.findIndex((language) => language === "en" || language.startsWith("en-"));
  const portugueseIndex = languages.findIndex((language) => language === "pt" || language.startsWith("pt-"));

  if (englishIndex >= 0 && (portugueseIndex < 0 || englishIndex < portugueseIndex)) return "en";
  return "pt";
}

